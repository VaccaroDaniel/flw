const state = {};
function bySection(sectionKey){ return PRACTICE_ITEMS.filter(x=>x.sectionKey===sectionKey).sort((a,b)=>a.itemNo-b.itemNo); }
function renderPractice(sectionKey){
  const items = bySection(sectionKey);
  if(!state[sectionKey]) state[sectionKey] = {page:0};
  const st = state[sectionKey];
  const maxPage = Math.ceil(items.length/3)-1;
  if(st.page<0) st.page=0; if(st.page>maxPage) st.page=maxPage;
  const start = st.page*3, subset = items.slice(start,start+3);
  const box = document.querySelector(`[data-practice="${sectionKey}"]`);
  if(!box) return;
  box.querySelector('.page-pill').textContent = `Practice ${start+1}–${Math.min(start+3, items.length)} of ${items.length}`;
  const list = box.querySelector('.practice-list');
  list.innerHTML = subset.map(item => itemHtml(item)).join('');
  box.querySelector('.prev-btn').disabled = st.page===0;
  box.querySelector('.next-btn').disabled = st.page===maxPage;
}
function itemHtml(item){
  const opts = item.options.map((o,idx)=>`<label class="option"><input type="radio" name="${item.id}" value="${idx}"><span>${escapeHtml(o.text)}</span></label>`).join('');
  return `<div class="practice-item" data-item="${item.id}">
    <div class="question">${escapeHtml(item.prompt)}</div>
    <div class="options">${opts}</div>
    <div class="check-row"><button class="btn" onclick="checkItem('${item.id}')">Check</button></div>
    <div class="feedback" aria-live="polite"></div>
  </div>`;
}
function checkItem(itemId){
  const item = PRACTICE_ITEMS.find(x=>x.id===itemId);
  const card = document.querySelector(`[data-item="${itemId}"]`);
  const chosen = card.querySelector(`input[name="${itemId}"]:checked`);
  const fb = card.querySelector('.feedback');
  const row = card.querySelector('.check-row');
  card.querySelectorAll('.answer').forEach(x=>x.remove());
  row.querySelectorAll('.retry,.show-answer').forEach(x=>x.remove());
  if(!chosen){ fb.className='feedback no'; fb.textContent='Choose one answer first.'; return; }
  const opt = item.options[Number(chosen.value)];
  if(opt.correct){
    fb.className='feedback ok'; fb.textContent=item.feedback || 'Correct.';
  }else{
    fb.className='feedback no'; fb.textContent='Try again.';
    const retry = document.createElement('button'); retry.className='btn warn retry'; retry.textContent='Try again'; retry.onclick=()=>{ card.querySelectorAll('input').forEach(i=>i.checked=false); fb.textContent=''; row.querySelectorAll('.retry,.show-answer').forEach(x=>x.remove()); card.querySelectorAll('.answer').forEach(x=>x.remove()); };
    const ans = document.createElement('button'); ans.className='btn secondary show-answer'; ans.textContent='Correct Answer'; ans.onclick=()=>showAnswer(itemId);
    row.append(retry, ans);
  }
}
function showAnswer(itemId){
  const item = PRACTICE_ITEMS.find(x=>x.id===itemId);
  const card = document.querySelector(`[data-item="${itemId}"]`);
  card.querySelectorAll('.answer').forEach(x=>x.remove());
  const div = document.createElement('div'); div.className='answer'; div.textContent='Correct answer: ' + item.correctAnswer;
  card.appendChild(div);
}
function nextPage(sectionKey){ state[sectionKey].page++; renderPractice(sectionKey); }
function prevPage(sectionKey){ state[sectionKey].page--; renderPractice(sectionKey); }
function escapeHtml(str){ return String(str).replace(/[&<>'"]/g, c=>({'&':'&amp;','<':'&lt;','>':'&gt;',"'":'&#39;','"':'&quot;'}[c])); }
function openImage(src){ const m=document.getElementById('imgModal'); const im=document.getElementById('modalImg'); im.src=src; m.classList.add('open'); }
function closeImage(){ document.getElementById('imgModal').classList.remove('open'); }
document.addEventListener('DOMContentLoaded',()=>{ document.querySelectorAll('[data-practice]').forEach(box=>renderPractice(box.dataset.practice)); });
